// AES-GCM credential envelope (plan §7). Web Crypto only; no runtime imports.
import { AppError } from "./errors";

export type SecretKind = "llm_provider" | "connector_token" | "webhook_secret";
const KEY_RE = /^[A-Za-z0-9+/]{43}=$/;
const ENVELOPE_RE = /^v1:([0-9a-f]{16}):([A-Za-z0-9+/]{16}):([A-Za-z0-9+/]+={0,2})$/;

function bytesToBase64(bytes: Uint8Array): string {
  let binary = "";
  for (const b of bytes) binary += String.fromCharCode(b);
  return btoa(binary);
}

function base64ToBytes(value: string): Uint8Array {
  try {
    const binary = atob(value);
    return Uint8Array.from(binary, (ch) => ch.charCodeAt(0));
  } catch {
    throw new AppError("SECRET_DECRYPT_FAILED", "密钥无法解密，请重新填写");
  }
}

function decodeKey(encoded: string): Uint8Array {
  const value = encoded.trim();
  if (!KEY_RE.test(value)) throw new AppError("SECRET_KEY_INVALID", "SDF_SECRET_KEY 必须是 32 字节随机值的 Base64");
  const bytes = base64ToBytes(value);
  if (bytes.length !== 32) throw new AppError("SECRET_KEY_INVALID", "SDF_SECRET_KEY 解码后必须是 32 字节");
  return bytes;
}

async function importKey(encoded: string, usages: KeyUsage[]): Promise<CryptoKey> {
  const bytes = decodeKey(encoded);
  return crypto.subtle.importKey("raw", bytes as BufferSource, { name: "AES-GCM" }, false, usages);
}

async function fingerprint(encoded: string): Promise<string> {
  const bytes = decodeKey(encoded);
  const digest = await crypto.subtle.digest("SHA-256", bytes as BufferSource);
  return Array.from(new Uint8Array(digest).slice(0, 8), (b) => b.toString(16).padStart(2, "0")).join("");
}

function aad(id: string, kind: SecretKind): Uint8Array {
  return new TextEncoder().encode(`sdf-secret:v1:${id}:${kind}`);
}

export interface EncryptedSecret {
  ciphertext: string;
  last4: string;
  keyId: string;
}

/** The id is generated by the caller first and is bound into AES-GCM AAD. */
export async function encryptSecret(
  plaintext: string,
  encodedKey: string,
  id: string,
  kind: SecretKind,
  iv = crypto.getRandomValues(new Uint8Array(12)),
): Promise<EncryptedSecret> {
  if (plaintext.length < 4) throw new AppError("VALIDATION", "密钥至少需要 4 个字符");
  if (iv.length !== 12) throw new AppError("INTERNAL", "加密 IV 长度不正确");
  const keyId = await fingerprint(encodedKey);
  const key = await importKey(encodedKey, ["encrypt"]);
  const encrypted = await crypto.subtle.encrypt(
    { name: "AES-GCM", iv: iv as BufferSource, additionalData: aad(id, kind) as BufferSource, tagLength: 128 },
    key,
    new TextEncoder().encode(plaintext) as BufferSource,
  );
  return {
    ciphertext: `v1:${keyId}:${bytesToBase64(iv)}:${bytesToBase64(new Uint8Array(encrypted))}`,
    last4: plaintext.slice(-4),
    keyId,
  };
}

export async function decryptSecret(envelope: string, encodedKey: string, id: string, kind: SecretKind): Promise<string> {
  const match = ENVELOPE_RE.exec(envelope);
  if (!match) throw new AppError("SECRET_DECRYPT_FAILED", "密钥无法解密，请重新填写");
  const [, keyId, iv64, cipher64] = match;
  if (keyId !== (await fingerprint(encodedKey))) throw new AppError("SECRET_DECRYPT_FAILED", "密钥无法解密，请重新填写");
  try {
    const key = await importKey(encodedKey, ["decrypt"]);
    const decrypted = await crypto.subtle.decrypt(
      { name: "AES-GCM", iv: base64ToBytes(iv64!) as BufferSource, additionalData: aad(id, kind) as BufferSource, tagLength: 128 },
      key,
      base64ToBytes(cipher64!) as BufferSource,
    );
    return new TextDecoder().decode(decrypted);
  } catch (error) {
    if (error instanceof AppError && error.code === "SECRET_KEY_INVALID") throw error;
    throw new AppError("SECRET_DECRYPT_FAILED", "密钥无法解密，请重新填写");
  }
}
